  id INT AUTO_INCREMENT PRIMARY KEY,
  abogado_a_cargo VARCHAR(255) NULL,
  proceso CHAR(23) NOT NULL,
  radicado_er VARCHAR(100) NULL,
  demandante VARCHAR(255) NULL,
  demandados VARCHAR(255) NULL,
  fecha_sentencia_primera_instancia DATE NULL,
  corporacion_primera_instancia VARCHAR(255) NULL,
  fecha_sentencia_segunda_instancia DATE NULL,
  corporacion_segunda_instancia VARCHAR(255) NULL,
  casacion VARCHAR(10) NULL,
  fecha_sentencia_casacion DATE NULL,
  corporacion_casacion VARCHAR(255) NULL,
  obligacion_hacer TEXT NULL,
  entidades_responsables VARCHAR(255) NULL,
  area_ministerio VARCHAR(255) NULL,
  nombre_responsable_gestion VARCHAR(255) NULL,
  plazo VARCHAR(100) NULL,
  fecha_asignacion_sentencia DATE NULL,
  fuente_recurso VARCHAR(255) NULL,
  valor DECIMAL(18,2) NULL,
  fecha_ultimo_seguimiento DATE NULL,
  observaciones TEXT NULL,
  estado VARCHAR(100) NULL,
  fecha_ejecutoria DATE NULL,
  fecha_alerta_maxima DATE NULL,
  fecha_maxima_cumplimiento DATE NULL,
  fecha_traslado_cumplimiento DATE NULL,
  validacion_oportunidad VARCHAR(20) NULL,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  INDEX idx_proceso (proceso)
);
