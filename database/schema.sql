-- ========== Modelo 1 · SEGUIMIENTO (cobro) ==========
CREATE TABLE IF NOT EXISTS seguimiento_cobro (
  id INT AUTO_INCREMENT PRIMARY KEY,
  no_ref VARCHAR(50) NULL,
  abogado_a_cargo VARCHAR(255) NULL,
  numero_proceso CHAR(23) NOT NULL,
  demandante VARCHAR(255) NULL,
  fecha_reporte DATE NULL,
  clase_proceso VARCHAR(255) NULL,
  demandado VARCHAR(255) NULL,
  fecha_segundo_fallo DATE NULL,
  fecha_ejecutoria DATE NULL,
  condena TEXT NULL,
  fecha_radicado_solicitud_cobro VARCHAR(100) NULL,
  estado_oaj VARCHAR(100) NULL,
  fecha_gestion DATE NULL,
  fecha_estimada_pago DATE NULL,
  observaciones TEXT NULL,
  firma_men VARCHAR(255) NULL,
  apoderado VARCHAR(255) NULL,
  valor_cuantia_estimada DECIMAL(18,2) NULL,
  resoluciones_pago VARCHAR(255) NULL,
  fecha_alerta_maxima DATE NULL,
  fecha_maxima_cumplimiento DATE NULL,
  fecha_traslado_cumplimiento DATE NULL,
  validacion_oportunidad VARCHAR(20) NULL,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  INDEX idx_numero_proceso (numero_proceso)
);

